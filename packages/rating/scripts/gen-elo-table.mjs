// Regenerates src/elo-table.ts. Floats are used here only; the engine reads the stored table.
// node packages/rating/scripts/gen-elo-table.mjs > packages/rating/src/elo-table.ts
const SCALE = 1_000_000;
const MAX = 2400;
const rows = [];
for (let d = 0; d <= MAX; d++) rows.push(Math.round(SCALE / (1 + Math.pow(10, -d / 400))));
let out = `// GENERATED by scripts/gen-elo-table.mjs. Do not edit. Part of ALGO_VERSION 1.\n`;
out += `// ELO_TABLE[d] = round(1e6 / (1 + 10^(-d/400))): chance a player d points higher finishes above, d = 0..${MAX}.\n`;
out += `// Beyond ${MAX} points the chance is below 1e-6 and is treated as exactly 1 (or 0).\n`;
out += `export const ELO_TABLE: readonly number[] = [\n`;
for (let i = 0; i < rows.length; i += 12) out += `  ${rows.slice(i, i + 12).join(', ')},\n`;
out += `];\n`;
process.stdout.write(out);
